CREATE TABLE shipment_income_and_costs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shipment_number VARCHAR(20)              NOT NULL,
    income          DECIMAL(19, 2)           NOT NULL,
    cost            DECIMAL(19, 2)           NOT NULL,
    additional_cost DECIMAL(19, 2)           NOT NULL,
    total_costs     DECIMAL(19, 2)           NOT NULL,
    profit_or_loss  DECIMAL(19, 2)           NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_shipment_income_and_costs PRIMARY KEY (id),
    CONSTRAINT fk_income_and_costs_shipment FOREIGN KEY (shipment_number) REFERENCES shipment (shipment_number)
);

CREATE INDEX idx_income_and_costs_shipment_date ON shipment_income_and_costs (shipment_number, created_at);
